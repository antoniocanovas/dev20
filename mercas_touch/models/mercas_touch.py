# Ways of invoicing lots to their supplier, as the buttons of the settlement wizard
LOT_INVOICE_MODES = ('settle', 'advance', 'firm')


def is_record_id(value):
    """ Whether `value`, sent by the screen, can be a record id. """
    return isinstance(value, int) and not isinstance(value, bool) and value > 0


def is_number(value):
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def check_uuid(env, value):
    """ Return the uuid generated by the screen, or raise if it isn't one. """
    try:
        return str(uuid.UUID(value))
    except (TypeError, ValueError, AttributeError):
        raise ValidationError(env._("Invalid identifier of the operation.")) from None


class MercasTouch(models.AbstractModel):
    """ Server side of the touch screen of the wholesale market.

    The screen loads what it shows with a few calls and makes each operation with a single call,
    which reuses the flows of `mercas_base` ("Sold & Sent", "Purchase & Receive", box returns,
    lot settlement). Each operation carries a uuid: sending it twice, after a double tap or a
    retry, returns the first result instead of duplicating the document. The access rights of
    the user apply as in the backend.
    """
    _name = 'mercas.touch'
    _description = "Mercas Touch Screen"

    # ------------------------------------------------------------------
    # Loading
    # ------------------------------------------------------------------

    @api.model
    def get_screen_data(self):
        """ Products by category, box products, payment journals and origin options. """
        company = self.env.company
        Product = self.env['product.product']
        products = Product.search([
            ('type', '=', 'consu'),
            '|', ('sale_ok', '=', True), ('purchase_ok', '=', True),
            *Product._check_company_domain(company),
        ], limit=PRODUCT_LIMIT, order='default_code, name, id')
        journals = self.env['account.journal'].search([
            ('type', 'in', ('bank', 'cash')),
            *self.env['account.journal']._check_company_domain(company),
        ], order='sequence, id')
        # With the origin filter of the company, only the countries and states marked as origin;
        # without it, every country, and the states of each country when it is chosen
        origin_domain = [('mercas_origin', '=', True)] if company.origin_filter else []
        countries = self.env['res.country'].search(origin_domain, order='name')
        states = self.env['res.country.state'].search(origin_domain, order='country_id, name') \
            if company.origin_filter else self.env['res.country.state']
        return {
            'company_id': company.id,
            'currency_id': company.currency_id.id,
            'products': [self._get_product_data(product) for product in products],
            'categories': [
                {'id': category.id, 'name': category.display_name}
                for category in products.categ_id.sorted('complete_name')
            ],
            'journals': [{'id': journal.id, 'name': journal.name, 'type': journal.type} for journal in journals],
            'origin': {
                'country': company.origin_country,
                'state': company.origin_state,
                'filter': company.origin_filter,
                'countries': [{'id': country.id, 'name': country.name} for country in countries],
                'states': [
                    {'id': state.id, 'name': state.name, 'country_id': state.country_id.id}
                    for state in states
                ],
            },
            'has_risk': 'risk_exception' in self.env['res.partner']._fields,
        }

    @api.model
    def get_origin_states(self, country_id):
        """ States of origin of a country, as the purchase offers them. """
        if not is_record_id(country_id):
            raise ValidationError(self.env._("Invalid country."))
        domain = [('country_id', '=', country_id)]
        if self.env.company.origin_filter:
            domain.append(('mercas_origin', '=', True))
        states = self.env['res.country.state'].search(domain, order='name')
        return [{'id': state.id, 'name': state.name, 'country_id': state.country_id.id} for state in states]

    def _get_product_data(self, product):
        return {
            'id': product.id,
            'name': product.display_name,
            'default_code': product.default_code or '',
            'barcode': product.barcode or '',
            'categ_id': product.categ_id.id,
            'uom': product.uom_id.name,
            'tracking': product.tracking or False,
            'is_box': product.is_box,
            'sale_ok': product.sale_ok,
            'purchase_ok': product.purchase_ok,
            'box_product_id': product.product_tmpl_id.box_product_id.id,
            'price': product.lst_price,
            'attributes': self._get_product_attributes(product),
            # Changes with the image, so that the browser cache is refreshed
            'image_unique': fields.Datetime.to_string(product.write_date) if product.image_128 else False,
        }

    def _get_product_attributes(self, product):
        """ Attributes chosen on each sale of the product, as the quality and the size of goods
        bought in bulk: the ones that never create variants, with more than one value. """
        return [{
            'id': ptal.id,
            'name': ptal.attribute_id.name,
            'values': [{'id': ptav.id, 'name': ptav.name} for ptav in ptal.product_template_value_ids],
        } for ptal in product.product_tmpl_id.valid_product_template_attribute_line_ids
            if ptal.attribute_id.create_variant == 'no_variant' and len(ptal.product_template_value_ids) > 1]

    @api.model
    def search_partners(self, query='', kind='customer'):
        """ Companies (and individuals) matching `query`, the most frequent customers or
        suppliers first. """
        if kind not in ('customer', 'supplier'):
            raise ValidationError(self.env._("Invalid kind of partner."))
        Partner = self.env['res.partner']
        domain = [('parent_id', '=', False), *Partner._check_company_domain(self.env.company)]
        query = (query or '').strip() if isinstance(query, str) else ''
        if query:
            domain += ['|', '|', '|', ('name', 'ilike', query), ('ref', 'ilike', query),
                       ('vat', 'ilike', query), ('phone', 'ilike', query)]
        rank = 'customer_rank' if kind == 'customer' else 'supplier_rank'
        partners = Partner.search(domain, limit=PARTNER_LIMIT, order=f'{rank} desc, name, id')
        return [{
            'id': partner.id,
            'name': partner.name,
            'city': partner.city or '',
            'vat': partner.vat or '',
            'ref': partner.ref or '',
        } for partner in partners]

    @api.model
    def get_partner_info(self, partner_id):
        """ Debt, risk, boxes and invoices to collect of a customer or supplier. """
        partner = self._get_partner(partner_id)
        company = self.env.company
        info = {
            'id': partner.id,
            'name': partner.name,
            'city': partner.city or '',
            'vat': partner.vat or '',
            'firm_negotiation': partner.mercas_firm_negotiation,
            'debt': self._get_debt(partner),
            'invoices': self._get_open_invoices(partner),
            'boxes': self._get_box_balance(partner),
        }
        # The credit limit and the risk are restricted to accounting users; shown here as information
        partner_sudo = partner.sudo().with_company(company)
        info['credit_limit'] = partner_sudo.credit_limit if partner_sudo.use_partner_credit_limit else 0.0
        if 'risk_exception' in partner._fields:
            info['risk'] = {
                'exception': partner_sudo.risk_exception,
                'total': partner_sudo.risk_total,
                'limit': partner_sudo.credit_limit,
            }
        return info

    def _get_partner(self, partner_id):
        if not is_record_id(partner_id):
            raise ValidationError(self.env._("Invalid partner."))
        partner = self.env['res.partner'].browse(partner_id).exists()
        if not partner:
            raise ValidationError(self.env._("The partner doesn't exist anymore."))
        partner.check_access('read')
        return partner.commercial_partner_id

    def _get_debt(self, partner):
        """ Overdue and not yet due receivable of the partner, in company currency. """
        debt = {'overdue': 0.0, 'not_due': 0.0}
        today = fields.Date.context_today(self)
        # The debt must count every invoice, also the ones of other salespeople
        groups = self.env['account.move.line'].sudo()._read_group(
            [
                ('partner_id', 'child_of', partner.id),
                ('company_id', '=', self.env.company.id),
                ('account_type', '=', 'asset_receivable'),
                ('parent_state', '=', 'posted'),
                ('reconciled', '=', False),
            ],
            ['date_maturity:day'],
            ['amount_residual:sum'],
        )
        for date_maturity, residual in groups:
            debt['overdue' if date_maturity and date_maturity < today else 'not_due'] += residual
        return debt

    def _get_open_invoices(self, partner):
        """ Invoices and credit notes still to collect, oldest due first. """
        today = fields.Date.context_today(self)
        moves = self.env['account.move'].sudo().search([
            ('commercial_partner_id', '=', partner.id),
            ('company_id', '=', self.env.company.id),
            ('move_type', 'in', ('out_invoice', 'out_refund')),
            ('state', '=', 'posted'),
            ('payment_state', 'in', ('not_paid', 'partial')),
        ], order='invoice_date_due, id')
        return [{
            'id': move.id,
            'name': move.name,
            'date_due': fields.Date.to_string(move.invoice_date_due),
            'residual': move.amount_residual_signed,
            'overdue': bool(move.invoice_date_due and move.invoice_date_due < today),
            'is_refund': move.move_type == 'out_refund',
        } for move in moves]

    def _get_box_balance(self, partner):
        """ Boxes of each kind held by the partner as a customer (positive: the customer has
        boxes of ours) and as a supplier (negative: we have boxes of the supplier). """
        company = self.env.company
        partner = partner.with_company(company)
        customer_location = partner.property_stock_customer
        supplier_location = partner.property_stock_supplier
        locations = partner._mercas_box_locations(company)
        balance = {}
        if locations:
            groups = self.env['stock.quant'].sudo()._read_group(
                [('location_id', 'in', locations.ids), ('product_id.is_box', '=', True)],
                ['product_id', 'location_id'], ['quantity:sum'],
            )
            for product, location, quantity in groups:
                line = balance.setdefault(product.id, {
                    'product_id': product.id, 'name': product.display_name, 'customer': 0.0, 'supplier': 0.0,
                })
                if location == customer_location:
                    line['customer'] += quantity
                elif location == supplier_location:
                    line['supplier'] += quantity
        return sorted(
            (line for line in balance.values() if line['customer'] or line['supplier']),
            key=lambda line: line['name'],
        )

    @api.model
    def get_product_lots(self, product_id):
        """ Lots of the product with stock available in the warehouse, oldest first. Lots
        already invoiced to their supplier aren't sold anymore, as in the sale order. """
        if not is_record_id(product_id):
            raise ValidationError(self.env._("Invalid product."))
        product = self.env['product.product'].browse(product_id).exists()
        if not product:
            raise ValidationError(self.env._("The product doesn't exist anymore."))
        groups = self.env['stock.quant']._read_group(
            [
                ('product_id', '=', product.id),
                ('location_id.usage', '=', 'internal'),
                ('lot_id', '!=', False),
                ('company_id', '=', self.env.company.id),
            ],
            ['lot_id'], ['quantity:sum', 'reserved_quantity:sum'],
        )
        lots = []
        for lot, quantity, reserved in groups:
            available = product.uom_id.round(quantity - reserved)
            if available <= 0 or lot.invoiced:
                continue
            lots.append(self._get_lot_data(lot, available))
        return sorted(lots, key=lambda lot: (lot['date'], lot['id']))

    def _get_lot_data(self, lot, available):
        origin = ', '.join(name for name in (lot.origin_state_id.name, lot.origin_country_id.name) if name)
        return {
            'id': lot.id,
            'name': lot.name,
            'product_id': lot.product_id.id,
            'available': available,
            'supplier': lot.partner_id.name or '',
            'origin': origin,
            'date': fields.Datetime.to_string(lot.create_date),
            'firm': lot.mercas_firm_negotiation,
        }

    @api.model
    def find_by_barcode(self, barcode):
        """ What a scanned code is: the lot of a box label (its name), or a product. """
        if not isinstance(barcode, str) or not barcode.strip():
            return {'lots': [], 'product_id': False}
        barcode = barcode.strip()
        lots = self.env['stock.lot'].search([
            ('name', '=', barcode),
            *self.env['stock.lot']._check_company_domain(self.env.company),
        ])
        found = []
        for lot in lots:
            available = sum(
                quant.quantity - quant.reserved_quantity
                for quant in lot.quant_ids if quant.location_id.usage == 'internal'
            )
            found.append(self._get_lot_data(lot, lot.product_id.uom_id.round(available)))
        product = self.env['product.product']
        if not found:
            product = product.search(['|', ('barcode', '=', barcode), ('default_code', '=', barcode)], limit=1)
        return {'lots': found, 'product_id': product.id}

    @api.model
    def get_lots(self, query=''):
        """ Lots not yet fully invoiced to their supplier, the last received first. """
        Lot = self.env['stock.lot']
        domain = [('invoiced', '=', False), *Lot._check_company_domain(self.env.company)]
        query = (query or '').strip() if isinstance(query, str) else ''
        if query:
            domain += ['|', '|', ('name', 'ilike', query), ('product_id', 'ilike', query), ('partner_id', 'ilike', query)]
        lots = Lot.search(domain, limit=LOT_LIMIT, order='create_date desc, id desc')
        return [self._get_lot_summary(lot) for lot in lots]

    @api.model
    def search_label_lots(self, query=''):
        """ Lots whose labels can be reprinted, invoiced or not: the ones named exactly as
        `query` first (a scanned or typed label), then the ones whose name, product or supplier
        contain it; without `query`, the last received. """
        Lot = self.env['stock.lot']
        company_domain = Lot._check_company_domain(self.env.company)
        query = (query or '').strip() if isinstance(query, str) else ''
        lots = Lot.browse()
        domain = list(company_domain)
        if query:
            lots = Lot.search([('name', '=ilike', escape_psql(query)), *company_domain], order='create_date desc, id desc')
            domain += [('id', 'not in', lots.ids),
                       '|', '|', ('name', 'ilike', query), ('product_id', 'ilike', query), ('partner_id', 'ilike', query)]
        lots |= Lot.search(domain, limit=LABEL_LOT_LIMIT, order='create_date desc, id desc')
        return [self._get_label_lot_data(lot, exact=lot.name.lower() == query.lower()) for lot in lots]

    def _get_label_lot_data(self, lot, exact=False):
        origin = ', '.join(name for name in (lot.origin_state_id.name, lot.origin_country_id.name) if name)
        return {
            'id': lot.id,
            'name': lot.name,
            'product': lot.product_id.display_name,
            'supplier': lot.partner_id.name or '',
            'origin': origin,
            'date': fields.Datetime.to_string(lot.create_date),
            'exact': exact,
        }

    @api.model
    def get_lot_label_action(self, lot_ids):
        """ The wizard of `mercas_base` to reprint the box labels of the lots, as many as boxes
        were bought of each one. """
        if not isinstance(lot_ids, list) or not lot_ids or not all(is_record_id(lot_id) for lot_id in lot_ids):
            raise ValidationError(self.env._("Choose the lots whose labels to print."))
        lots = self.env['stock.lot'].browse(lot_ids).exists()
        if len(lots) != len(set(lot_ids)):
            raise ValidationError(self.env._("Some lots don't exist anymore."))
        lots.check_access('read')
        return self._get_client_action(lots.action_print_mercas_labels())

    def _get_lot_summary(self, lot):
        return {
            'id': lot.id,
            'name': lot.name,
            'product': lot.product_id.display_name,
            'uom': lot.product_id.uom_id.name,
            'supplier': lot.partner_id.name or '',
            'date': fields.Datetime.to_string(lot.create_date),
            'firm': lot.mercas_firm_negotiation,
            'purchased': lot.purchase_kg,
            'received': lot.received_kg,
            'sold': lot.sale_kg,
            'scrapped': lot.scrap_kg,
            'stock': lot.product_qty,
            'sale_amount': lot.sale_amount,
            'supplier_amount': lot.supplier_amount,
            'completed': lot.completed,
            'invoiceable': lot.invoiceable,
        }

