    def _get_client_action(self, action):
        """ An action returned by a button of the backend, ready for the web client: the
        screen calls the server directly, without the cleaning of the buttons (the views of a
        window action, among others). """
        return clean_action(action, self.env)

    def _check_operation(self, vals):
        if not isinstance(vals, dict):
            raise ValidationError(self.env._("Invalid operation."))
        return vals, check_uuid(self.env, vals.get('uuid'))

    def _prepare_lines(self, lines, kind):
        """ Check the lines sent by the screen for a sale, a purchase or a box movement. """
        if not isinstance(lines, list) or not lines or len(lines) > MAX_LINES:
            raise ValidationError(self.env._("Add between 1 and %s lines.", MAX_LINES))
        Product = self.env['product.product']
        prepared = []
        for line in lines:
            if not isinstance(line, dict):
                raise ValidationError(self.env._("Invalid line."))
            product_id, qty = line.get('product_id'), line.get('qty')
            if not is_record_id(product_id):
                raise ValidationError(self.env._("Invalid product."))
            if not is_number(qty) or qty <= 0:
                raise ValidationError(self.env._("The quantity must be positive."))
            vals = {'product_id': product_id, 'qty': qty}
            if kind != 'box':
                vals.update(self._prepare_line_options(line, kind))
            prepared.append(vals)
        products = Product.browse({line['product_id'] for line in prepared}).exists()
        products.check_access('read')
        if len(products) != len({line['product_id'] for line in prepared}):
            raise ValidationError(self.env._("Some products don't exist anymore."))
        allowed = {'sale': 'sale_ok', 'purchase': 'purchase_ok'}.get(kind)
        if allowed and not all(products.mapped(allowed)):
            raise ValidationError(self.env._("Some products can't be sold or bought."))
        if kind == 'box' and not all(products.mapped('is_box')):
            raise ValidationError(self.env._("Only boxes can be returned or delivered."))
        lots = self.env['stock.lot'].browse({line['lot_id'] for line in prepared if 'lot_id' in line}).exists()
        for line in prepared:
            if 'lot_id' in line and lots.browse(line['lot_id']).product_id.id != line['product_id']:
                raise ValidationError(self.env._("The lot doesn't belong to the product."))
        boxes = Product.browse({line['box_product_id'] for line in prepared if line.get('box_product_id')}).exists()
        if not all(boxes.mapped('is_box')) or len(boxes) != len({
                line['box_product_id'] for line in prepared if line.get('box_product_id')}):
            raise ValidationError(self.env._("Invalid box."))
        return prepared

    def _prepare_line_options(self, line, kind):
        vals = {}
        for key in ('lot_id', 'box_product_id', 'origin_country_id', 'origin_state_id'):
            value = line.get(key)
            if value is None or value is False:
                continue
            if not is_record_id(value):
                raise ValidationError(self.env._("Invalid line."))
            vals[key] = value
        if kind != 'purchase':
            vals.pop('origin_country_id', None)
            vals.pop('origin_state_id', None)
        price = line.get('price_unit')
        if price is not None:
            if not is_number(price) or price < 0:
                raise ValidationError(self.env._("The price can't be negative."))
            vals['price_unit'] = price
        box_qty = line.get('box_qty')
        if box_qty is not None:
            if not isinstance(box_qty, int) or isinstance(box_qty, bool) or box_qty < 0:
                raise ValidationError(self.env._("The number of boxes must be a positive whole number."))
            vals['box_qty'] = box_qty
        if kind == 'purchase':
            if 'firm' in line:
                if not isinstance(line['firm'], bool):
                    raise ValidationError(self.env._("Invalid line."))
                vals['firm'] = line['firm']
            lot_name = line.get('lot_name')
            if lot_name:
                if not isinstance(lot_name, str) or len(lot_name.strip()) > 128:
                    raise ValidationError(self.env._("Invalid lot name."))
                vals['lot_name'] = lot_name.strip()
        note = line.get('note')
        if note:
            if not isinstance(note, str) or len(note) > MAX_NOTE_LENGTH:
                raise ValidationError(self.env._(
                    "The text of a line can't be longer than %s characters.", MAX_NOTE_LENGTH))
            vals['note'] = note.strip()
        return vals

    def _add_line_notes(self, order_lines, lines):
        """ Write the text of each line under the description of its product. Order lines are
        created in the order of the lines of the screen; the box lines come after them. """
        product_lines = order_lines.filtered(lambda line: not line.display_type)
        for order_line, line in zip(product_lines, lines):
            if line.get('note'):
                order_line.name = '\n'.join(part for part in (order_line.name, line['note']) if part)

    def _notify_lots_changed(self, products):
        """ Tell the screens open elsewhere that the stock of the lots of `products` changed. """
        self.env['bus.bus']._sendone(self.env.ref('base.group_user'), LOTS_CHANGED, {
            'company_id': self.env.company.id,
            'product_ids': products.ids,
        })
