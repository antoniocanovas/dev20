    @api.model
    def sell(self, vals):
        """ Sell and deliver at once, as "Sold & Sent" does in the sale order.

        :param dict vals: {
            'uuid': str, 'partner_id': int,
            'lines': [{'product_id': int, 'qty': float, 'lot_id': int (optional),
                       'price_unit': float (optional), 'box_qty': int (optional),
                       'box_product_id': int (optional), 'note': str (optional)}],
        }
        :return: {'order': {...}} and, if the customer exceeds their risk, the 'action' of the
            standard risk dialog; the order stays as a quotation until it is accepted there.
        """
        vals, operation_uuid = self._check_operation(vals)
        existing = self.env['sale.order'].search([('mercas_touch_uuid', '=', operation_uuid)], limit=1)
        if existing:
            return {'order': self._get_sale_result(existing)}
        partner = self._get_partner(vals.get('partner_id'))
        lines = self._prepare_lines(vals.get('lines'), 'sale')
        order = self.env['sale.order'].create({
            'partner_id': partner.id,
            'mercas_touch_uuid': operation_uuid,
            'order_line': [Command.create(self._get_sale_line_vals(line)) for line in lines],
        })
        self._add_line_notes(order.order_line, lines)
        action = order.button_sold_and_sent()
        self._notify_lots_changed(order.order_line.product_id)
        result = {'order': self._get_sale_result(order)}
        if isinstance(action, dict):
            result['action'] = self._get_client_action(action)
        return result

    def _get_sale_line_vals(self, line):
        vals = {'product_id': line['product_id'], 'product_uom_qty': line['qty']}
        for key in ('lot_id', 'price_unit', 'box_qty', 'box_product_id'):
            if key in line:
                vals[key] = line[key]
        return vals

    def _get_sale_result(self, order):
        return {
            'id': order.id,
            'name': order.name,
            'state': order.state,
            'amount_total': order.amount_total,
            'delivered': bool(order.picking_ids) and all(
                picking.state in ('done', 'cancel') for picking in order.picking_ids),
            'picking_ids': order.picking_ids.filtered(lambda picking: picking.state == 'done').ids,
        }

    @api.model
    def purchase(self, vals):
        """ Buy and receive at once, as "Purchase & Receive" does in the purchase order. Each
        tracked line gets a lot: the one named on the screen, or a new one.

        :param dict vals: {
            'uuid': str, 'partner_id': int,
            'lines': [{'product_id': int, 'qty': float, 'price_unit': float (optional),
                       'box_qty': int (optional), 'box_product_id': int (optional),
                       'origin_country_id': int (optional), 'origin_state_id': int (optional),
                       'firm': bool (optional), 'lot_name': str (optional),
                       'note': str (optional)}],
        }
        """
        vals, operation_uuid = self._check_operation(vals)
        existing = self.env['purchase.order'].search([('mercas_touch_uuid', '=', operation_uuid)], limit=1)
        if existing:
            return {'order': self._get_purchase_result(existing)}
        partner = self._get_partner(vals.get('partner_id'))
        lines = self._prepare_lines(vals.get('lines'), 'purchase')
        order = self.env['purchase.order'].create({
            'partner_id': partner.id,
            'mercas_touch_uuid': operation_uuid,
            'order_line': [Command.create(self._get_purchase_line_vals(line, partner)) for line in lines],
        })
        self._add_line_notes(order.order_line, lines)
        order._mercas_autocreate_lots()
        order.button_purchase_and_receive()
        self._notify_lots_changed(order.order_line.product_id)
        return {'order': self._get_purchase_result(order)}

    def _get_purchase_line_vals(self, line, partner):
        vals = {'product_id': line['product_id'], 'product_qty': line['qty']}
        for key in ('price_unit', 'box_qty', 'box_product_id', 'origin_country_id', 'origin_state_id'):
            if key in line:
                vals[key] = line[key]
        if 'firm' in line:
            vals['mercas_firm_negotiation'] = line['firm']
        if line.get('lot_name'):
            vals['lot_id'] = self._get_purchase_lot(line, partner).id
        return vals

    def _get_purchase_lot(self, line, partner):
        """ The lot named on the screen: an existing lot of the product, or a new one. """
        Lot = self.env['stock.lot']
        lot = Lot.search([
            ('name', '=', line['lot_name']),
            ('product_id', '=', line['product_id']),
            *Lot._check_company_domain(self.env.company),
        ], limit=1)
        return lot or Lot.create({
            'name': line['lot_name'],
            'product_id': line['product_id'],
            'company_id': self.env.company.id,
            'partner_id': partner.id,
            'origin_country_id': line.get('origin_country_id', False),
            'origin_state_id': line.get('origin_state_id', False),
            'mercas_firm_negotiation': line.get('firm', partner.mercas_firm_negotiation),
        })

    def _get_purchase_result(self, order):
        product_lines = order.order_line.filtered(lambda line: not line.display_type and not line.box_purchase_line_id)
        return {
            'id': order.id,
            'name': order.name,
            'state': order.state,
            'amount_total': order.amount_total,
            'received': bool(order.picking_ids) and all(
                picking.state in ('done', 'cancel') for picking in order.picking_ids),
            'lots': [{
                'product': line.product_id.display_name,
                'lot_id': line.lot_id.id,
                'lot_name': line.lot_id.name or '',
                'box_qty': line.box_qty,
            } for line in product_lines if line.lot_id],
        }

    @api.model
    def move_boxes(self, vals):
        """ Boxes given back by a customer, or given back to a supplier, with the box flows of
        `mercas_base`: a purchase of boxes received and invoiced (the deposit is refunded), or
        a sale of boxes delivered and invoiced.

        :param dict vals: {
            'uuid': str, 'partner_id': int, 'direction': 'return' or 'deliver',
            'lines': [{'product_id': int, 'qty': float}],
        }
        """
        vals, operation_uuid = self._check_operation(vals)
        direction = vals.get('direction')
        if direction not in ('return', 'deliver'):
            raise ValidationError(self.env._("Invalid box movement."))
        model = 'purchase.order' if direction == 'return' else 'sale.order'
        existing = self.env[model].search([('mercas_touch_uuid', '=', operation_uuid)], limit=1)
        partner = self._get_partner(vals.get('partner_id'))
        if existing:
            return {'order': self._get_box_result(existing), 'boxes': self._get_box_balance(partner)}
        lines = self._prepare_lines(vals.get('lines'), 'box')
        result = {}
        if direction == 'return':
            order = self.env['purchase.order'].create({
                'partner_id': partner.id,
                'mercas_touch_uuid': operation_uuid,
                'order_line': [Command.create({'product_id': line['product_id'], 'product_qty': line['qty']})
                               for line in lines],
            })
            order.button_purchase_and_receive()
        else:
            order = self.env['sale.order'].create({
                'partner_id': partner.id,
                'mercas_touch_uuid': operation_uuid,
                'order_line': [Command.create({'product_id': line['product_id'], 'product_uom_qty': line['qty']})
                               for line in lines],
            })
            action = order.button_sold_and_sent()
            if isinstance(action, dict):
                result['action'] = self._get_client_action(action)
        result.update(order=self._get_box_result(order), boxes=self._get_box_balance(partner))
        return result

    def _get_box_result(self, order):
        return {
            'id': order.id,
            'name': order.name,
            'model': order._name,
            'state': order.state,
            'invoice_ids': order.invoice_ids.ids,
        }

    @api.model
    def scrap_lot(self, lot_id, qty):
        """ Scrap `qty` of the lot from the internal location where it has the most stock. """
        if not is_record_id(lot_id):
            raise ValidationError(self.env._("Invalid lot."))
        if not is_number(qty) or qty <= 0:
            raise ValidationError(self.env._("The quantity must be positive."))
        lot = self.env['stock.lot'].browse(lot_id).exists()
        if not lot:
            raise ValidationError(self.env._("The lot doesn't exist anymore."))
        quants = lot.quant_ids.filtered(lambda quant: quant.location_id.usage == 'internal' and quant.quantity > 0)
        if not quants:
            raise UserError(self.env._("The lot %s has no stock to scrap.", lot.name))
        location = max(quants, key=lambda quant: quant.quantity).location_id
        scrap = self.env['stock.move'].create({
            'is_scrap': True,
            'product_id': lot.product_id.id,
            'lot_ids': lot.ids,
            'quantity': qty,
            'uom_id': lot.product_id.uom_id.id,
            'location_id': location.id,
            'location_dest_id': self.env.company.scrap_location_id.id,
            'company_id': self.env.company.id,
        })
        if isinstance(scrap.action_scrap(), dict):
            # Not enough stock: the standard asks for confirmation, the screen doesn't scrap
            raise UserError(self.env._(
                "There isn't enough stock of the lot %(lot)s in %(location)s to scrap %(qty)s.",
                lot=lot.name, location=location.display_name, qty=qty,
            ))
        self._notify_lots_changed(lot.product_id)
        return self._get_lot_summary(lot)

    @api.model
    def invoice_lots(self, lot_ids, mode):
        """ Invoice the lots to their supplier, as the buttons of the settlement wizard.

        - 'settle': completed lots under sale settlement and lots under firm negotiation;
        - 'advance': an advance on lots under sale settlement that still have stock;
        - 'firm': the received quantity still to invoice of lots under firm negotiation.

        :return: the action opening the invoices made
        """
        if mode not in LOT_INVOICE_MODES:
            raise ValidationError(self.env._("Invalid way of invoicing."))
        if not isinstance(lot_ids, list) or not lot_ids or not all(is_record_id(lot_id) for lot_id in lot_ids):
            raise ValidationError(self.env._("Select the lots to invoice."))
        lots = self.env['stock.lot'].browse(lot_ids).exists()
        if mode == 'settle':
            lots = lots.filtered(lambda lot: lot.mercas_firm_negotiation or lot.completed)
        elif mode == 'advance' and (firm := lots.filtered('mercas_firm_negotiation')):
            raise UserError(self.env._(
                "The following lots are under firm negotiation: %s. Invoice them with \"Firm invoice\".",
                ', '.join(firm.mapped('name')),
            ))
        elif mode == 'firm' and (not_firm := lots.filtered(lambda lot: not lot.mercas_firm_negotiation)):
            raise UserError(self.env._(
                "The following lots don't have firm negotiation: %s.",
                ', '.join(not_firm.mapped('name')),
            ))
        lots = lots.filtered('invoiceable')
        if not lots:
            raise UserError(self.env._("There are no lots to invoice."))
        action = lots.action_create_supplier_invoices()
        return self._get_client_action(action) if action else False

    @api.model
    def register_payment(self, vals):
        """ Collect a payment of a customer, reconciled with the invoices chosen on the screen.

        :param dict vals: {
            'uuid': str, 'partner_id': int, 'amount': float, 'journal_id': int,
            'invoice_ids': [int] (optional), 'memo': str (optional),
        }
        """
        vals, operation_uuid = self._check_operation(vals)
        Payment = self.env['account.payment']
        existing = Payment.search([('mercas_touch_uuid', '=', operation_uuid)], limit=1)
        if existing:
            return self._get_payment_result(existing)
        partner = self._get_partner(vals.get('partner_id'))
        amount = vals.get('amount')
        if not is_number(amount) or amount <= 0:
            raise ValidationError(self.env._("The amount must be positive."))
        journal_id = vals.get('journal_id')
        journal = self.env['account.journal'].browse(journal_id).exists() if is_record_id(journal_id) else None
        if not journal or journal.type not in ('bank', 'cash'):
            raise ValidationError(self.env._("Choose a bank or cash journal."))
        memo = vals.get('memo') or ''
        if not isinstance(memo, str):
            raise ValidationError(self.env._("Invalid memo."))
        invoice_ids = vals.get('invoice_ids') or []
        if not isinstance(invoice_ids, list) or not all(is_record_id(invoice_id) for invoice_id in invoice_ids):
            raise ValidationError(self.env._("Invalid invoices."))
        invoices = self.env['account.move'].browse(invoice_ids).exists()
        if len(invoices) != len(invoice_ids) or any(
            invoice.commercial_partner_id != partner or invoice.state != 'posted'
            or invoice.move_type not in ('out_invoice', 'out_refund')
            or invoice.payment_state not in ('not_paid', 'partial')
            for invoice in invoices
        ):
            raise ValidationError(self.env._("Some invoices can't be paid anymore."))
        if invoices:
            wizard = self.env['account.payment.register'].with_context(
                active_model='account.move', active_ids=invoices.ids,
            ).create({
                'amount': amount,
                'journal_id': journal.id,
                'payment_date': fields.Date.context_today(self),
                'group_payment': True,
                **({'communication': memo} if memo else {}),
            })
            payment = wizard._create_payments()
            payment.mercas_touch_uuid = operation_uuid
        else:
            payment = Payment.create({
                'payment_type': 'inbound',
                'partner_type': 'customer',
                'partner_id': partner.id,
                'amount': amount,
                'journal_id': journal.id,
                'memo': memo,
                'mercas_touch_uuid': operation_uuid,
            })
            payment.action_post()
        return self._get_payment_result(payment)

    def _get_payment_result(self, payment):
        return {'id': payment.id, 'name': payment.name, 'amount': payment.amount, 'state': payment.state}

    @api.model
    def get_print_action(self, model, order_id, kind):
        """ What to print after an operation: the delivery slip of a sale, or the box labels
        of a sale or a purchase (the wizard of `mercas_base`, to choose how many). """
        if model not in ('sale.order', 'purchase.order') or kind not in ('delivery', 'labels'):
            raise ValidationError(self.env._("Nothing to print."))
        if not is_record_id(order_id):
            raise ValidationError(self.env._("Invalid order."))
        order = self.env[model].browse(order_id).exists()
        if not order:
            raise ValidationError(self.env._("The order doesn't exist anymore."))
        if kind == 'labels':
            return self._get_client_action(order.action_print_mercas_labels())
        pickings = order.picking_ids.filtered(lambda picking: picking.state == 'done')
        if model != 'sale.order' or not pickings:
            raise UserError(self.env._("There is no delivery to print."))
        return self._get_client_action(self.env.ref('stock.action_report_delivery').report_action(pickings))

