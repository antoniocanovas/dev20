import uuid
from collections import defaultdict
from datetime import timedelta

from odoo import api, fields, models
from odoo.exceptions import AccessError, ValidationError

# Customers' products that the tablet proposes in a new order
USUAL_PRODUCT_LIMIT = 30
# Orders of the last year make the usual products
USUAL_PRODUCT_DAYS = 365
# Products that can be added to an order out of the usual ones
CATALOG_LIMIT = 500
# Most uuids that the tablet asks for at once
SYNC_STATUS_LIMIT = 500


def _get_tax_percent(taxes):
    """ Percentage of `taxes` added to the price; taxes included in the price count as 0. """
    return sum(
        tax.amount for tax in taxes.flatten_taxes_hierarchy()
        if tax.amount_type == 'percent' and not tax.price_include
    )


def is_record_id(value):
    """ Whether `value`, sent by the tablet, can be a record id. """
    return isinstance(value, int) and not isinstance(value, bool) and value > 0


def check_offline_uuid(env, value):
    """ Return the uuid generated by the tablet, or raise if it isn't one. """
    try:
        return str(uuid.UUID(value))
    except (TypeError, ValueError, AttributeError):
        raise ValidationError(env._("Invalid offline identifier.")) from None


class ResPartner(models.Model):
    _inherit = 'res.partner'

    @api.model
    def get_route_data(self):
        """ Everything the tablet needs to work offline on the route of the current salesperson:
        customers with their debt, pending invoices, recent orders and usual products with their
        prices, a catalog to add other products and the journals to register payments.

        The tablet keeps the result in its offline cache, so the call takes no argument: the
        same call always reads the same cache entry.
        """
        self._check_route_salesperson()
        company = self.env.company
        customers = self.search([('user_id', '=', self.env.uid), ('parent_id', '=', False)], order='name')
        debts = customers._get_route_debts()
        invoices = customers._get_route_invoices()
        orders = customers._get_route_orders(company.route_order_count)
        usual = customers._get_route_usual_products()
        products = self.env['product.product'].search(
            [('sale_ok', '=', True), *self.env['product.product']._check_company_domain(company)],
            limit=CATALOG_LIMIT, order='default_code, name, id',
        )
        products |= self.env['product.product'].browse(
            {line['product_id'] for lines in usual.values() for line in lines})
        prices, price_keys = customers._get_route_prices(products)
        taxes, tax_keys = customers._get_route_taxes(products)
        # The credit limit is restricted to accounting users; salespeople only read it here
        credit_limits = {
            customer.id: customer.credit_limit for customer in customers.sudo()
        } if company.account_use_credit_limit else {}
        has_discount = self.env.user.has_group('sale.group_discount_per_so_line')

        customer_list = []
        for customer in customers:
            price_key, tax_key = price_keys[customer.id], tax_keys[customer.id]
            customer_list.append({
                'id': customer.id,
                'name': customer.name,
                'street': ' '.join(filter(None, [customer.street, customer.street2])),
                'city': ' '.join(filter(None, [customer.zip, customer.city])),
                'phone': customer.phone or '',
                'overdue': debts[customer.id]['overdue'],
                'not_due': debts[customer.id]['not_due'],
                'credit_limit': credit_limits.get(customer.id, False),
                'price_key': price_key,
                'tax_key': tax_key,
                'invoices': invoices[customer.id],
                'orders': orders[customer.id],
                'usual_products': [dict(
                    line,
                    price=prices[price_key][line['product_id']],
                    discount=line['discount'] if has_discount else 0.0,
                    tax_percent=taxes[tax_key][line['product_id']],
                ) for line in usual[customer.id]],
            })
        return {
            'generated_at': fields.Datetime.to_string(fields.Datetime.now()),
            'currency_id': company.currency_id.id,
            'has_discount': has_discount,
            'customers': customer_list,
            'products': [{
                'id': product.id,
                'name': product.display_name,
                'default_code': product.default_code or '',
                'uom_name': product.uom_id.name,
                'categ_id': product.categ_id.id,
                # Changes when the image changes: the tablet keeps the image in the browser cache
                'image_unique': fields.Datetime.to_string(product.write_date),
            } for product in products],
            'categories': [{
                'id': category.id,
                'name': category.complete_name,
            } for category in products.categ_id.sorted('complete_name')],
            'prices': prices,
            'taxes': taxes,
            'journals': [{
                'id': journal.id,
                'name': journal.name,
                'type': journal.type,
            } for journal in company._get_route_payment_journals()],
        }

    @api.model
    def get_route_sync_status(self, uuids):
        """ Return which orders and payments made on the tablet by the current user reached the
        server, and which version of each order, so that the tablet stops showing them as pending.

        :return: {uuid: revision}; payments are never changed, their revision is always 1
        """
        self._check_route_salesperson()
        if not isinstance(uuids, list) or len(uuids) > SYNC_STATUS_LIMIT:
            raise ValidationError(self.env._("Invalid list of offline identifiers."))
        uuids = [check_offline_uuid(self.env, value) for value in uuids]
        domain = [('offline_uuid', 'in', uuids), ('create_uid', '=', self.env.uid)]
        status = {order.offline_uuid: order.offline_revision for order in self.env['sale.order'].search(domain)}
        # Salespeople can't read payments; only the uuids of their own payments are returned
        status.update(dict.fromkeys(self.env['account.payment'].sudo().search(domain).mapped('offline_uuid'), 1))
        return status

    # ---- Helpers ----

    def _check_route_salesperson(self):
        if not self.env.user.has_group('sales_team.group_sale_salesman'):
            raise AccessError(self.env._("Only salespeople can use the route sales."))

    @api.model
    def _get_route_customer(self, partner_id):
        """ Return the commercial partner of `partner_id` if it is in the route of the current
        salesperson, or raise. Used to validate what the tablet sends. """
        self._check_route_salesperson()
        if not is_record_id(partner_id):
            raise ValidationError(self.env._("Invalid customer."))
        customer = self.browse(partner_id).exists().commercial_partner_id
        if not customer or customer.user_id != self.env.user:
            raise AccessError(self.env._("This customer is not in your route."))
        return customer

    def _get_route_debts(self):
        """ Overdue and not yet due receivable of each customer, in company currency. """
        debts = {customer.id: {'overdue': 0.0, 'not_due': 0.0} for customer in self}
        if not self:
            return debts
        today = fields.Date.context_today(self)
        # Salespeople only read their own invoices; the debt must count every invoice
        lines = self.env['account.move.line'].sudo()._read_group(
            [
                ('partner_id', 'in', self.ids),
                ('company_id', '=', self.env.company.id),
                ('account_type', '=', 'asset_receivable'),
                ('parent_state', '=', 'posted'),
                ('reconciled', '=', False),
            ],
            ['partner_id', 'date_maturity:day'],
            ['amount_residual:sum'],
        )
        for partner, date_maturity, residual in lines:
            key = 'overdue' if date_maturity and date_maturity < today else 'not_due'
            debts[partner.id][key] += residual
        return debts

    def _get_route_invoices(self):
        """ Invoices and credit notes still to pay of each customer, oldest due first. """
        invoices = {customer.id: [] for customer in self}
        if not self:
            return invoices
        today = fields.Date.context_today(self)
        # Salespeople only read their own invoices; every pending invoice must be collectable
        moves = self.env['account.move'].sudo().search([
            ('commercial_partner_id', 'in', self.ids),
            ('company_id', '=', self.env.company.id),
            ('move_type', 'in', ('out_invoice', 'out_refund')),
            ('state', '=', 'posted'),
            ('payment_state', 'in', ('not_paid', 'partial')),
        ], order='invoice_date_due, id')
        for move in moves:
            invoices[move.commercial_partner_id.id].append({
                'id': move.id,
                'name': move.name,
                'date_due': fields.Date.to_string(move.invoice_date_due),
                'residual': move.amount_residual_signed,
                'overdue': bool(move.invoice_date_due and move.invoice_date_due < today),
                'is_refund': move.move_type == 'out_refund',
            })
        return invoices

    def _get_route_orders(self, limit):
        """ The `limit` most recent orders of each customer, with their lines. """
        orders = {customer.id: [] for customer in self}
        if not self or limit <= 0:
            return orders
        SaleOrder = self.env['sale.order']
        groups = SaleOrder._read_group(
            [('partner_id', 'child_of', self.ids), ('state', '!=', 'cancel')],
            ['partner_id'], ['id:array_agg'],
        )
        ids_by_customer = defaultdict(list)
        for partner, order_ids in groups:
            ids_by_customer[partner.commercial_partner_id.id] += order_ids
        recent_ids = []
        for order_ids in ids_by_customer.values():
            # The highest ids are the last orders created
            recent_ids += sorted(order_ids, reverse=True)[:limit]
        state_names = dict(SaleOrder._fields['state']._description_selection(self.env))
        invoice_status_names = dict(SaleOrder._fields['invoice_status']._description_selection(self.env))
        for order in SaleOrder.browse(recent_ids).sorted('date_order', reverse=True):
            orders[order.partner_id.commercial_partner_id.id].append({
                'id': order.id,
                'name': order.name,
                'date': fields.Datetime.to_string(order.date_order),
                'state': state_names.get(order.state, order.state),
                'state_code': order.state,
                'invoice_status': invoice_status_names.get(order.invoice_status, ''),
                'invoice_status_code': order.invoice_status or '',
                # Like the list of the orders: delivered, else promised, else expected
                'delivery_date': fields.Datetime.to_string(order.delivery_date),
                'commitment_date': fields.Datetime.to_string(order.commitment_date),
                'amount_total': order.amount_total,
                'currency_id': order.currency_id.id,
                # To change a quotation on the tablet
                'offline_uuid': order.offline_uuid or False,
                'offline_revision': order.offline_revision,
                'lines': [{
                    'line_id': line.id,
                    'product_id': line.product_id.id,
                    'name': line.product_id.display_name,
                    'qty': line.product_uom_qty,
                    'uom_name': line.product_uom_id.name,
                    'price_unit': line.price_unit,
                    'discount': line.discount,
                    'tax_percent': _get_tax_percent(line.tax_ids),
                    'subtotal': line.price_subtotal,
                } for line in order.order_line if not line.display_type and line.product_id],
            })
        return orders

    def _get_route_usual_products(self):
        """ Products the customers bought in the last year, most often bought first, with the
        average quantity and discount. """
        usual = {customer.id: [] for customer in self}
        if not self:
            return usual
        date_from = fields.Datetime.now() - timedelta(days=USUAL_PRODUCT_DAYS)
        groups = self.env['sale.order.line']._read_group(
            [
                ('order_partner_id', 'child_of', self.ids),
                ('state', '=', 'sale'),
                ('display_type', '=', False),
                ('product_id.sale_ok', '=', True),
                ('order_id.date_order', '>=', date_from),
            ],
            ['order_partner_id', 'product_id'],
            ['__count', 'product_uom_qty:sum', 'discount:sum'],
        )
        # Contacts of a customer add up to their company
        stats = defaultdict(lambda: [0, 0.0, 0.0])
        for partner, product, count, qty, discount in groups:
            stat = stats[partner.commercial_partner_id.id, product.id]
            stat[0] += count
            stat[1] += qty
            stat[2] += discount
        by_customer = defaultdict(list)
        for (customer_id, product_id), (count, qty, discount) in stats.items():
            by_customer[customer_id].append((count, product_id, qty / count, discount / count))
        for customer_id, lines in by_customer.items():
            lines.sort(key=lambda line: (-line[0], line[1]))
            usual[customer_id] = [{
                'product_id': product_id,
                'qty': round(qty, 2),
                'discount': round(discount, 2),
                'count': count,
            } for count, product_id, qty, discount in lines[:USUAL_PRODUCT_LIMIT]]
        return usual

    def _get_route_prices(self, products):
        """ Price of `products` for each pricelist of the customers.

        :return: ({price_key: {product_id: price}}, {customer_id: price_key}); the key is the
            pricelist id, or 0 for the customers without pricelist (sales price).
        """
        price_keys = {customer.id: customer.property_product_pricelist.id or 0 for customer in self}
        prices = {}
        for key in set(price_keys.values()):
            if key:
                pricelist = self.env['product.pricelist'].browse(key)
                prices[key] = pricelist._get_products_price(products, 1.0, currency=pricelist.currency_id)
            else:
                prices[key] = {product.id: product.lst_price for product in products}
        return prices, price_keys

    def _get_route_taxes(self, products):
        """ Tax percentage of `products` added to the price, for each fiscal position of the
        customers. Taxes included in the price count as 0.

        :return: ({tax_key: {product_id: percent}}, {customer_id: tax_key}); the key is the fiscal
            position id, or 0 without fiscal position.
        """
        company = self.env.company
        FiscalPosition = self.env['account.fiscal.position']
        tax_keys = {customer.id: FiscalPosition._get_fiscal_position(customer).id or 0 for customer in self}
        company_domain = self.env['account.tax']._check_company_domain(company)
        taxes = {}
        for key in set(tax_keys.values()):
            fiscal_position = FiscalPosition.browse(key)
            taxes[key] = {}
            for product in products:
                product_taxes = product.taxes_id.filtered_domain(company_domain)
                if fiscal_position:
                    product_taxes = fiscal_position.map_tax(product_taxes)
                taxes[key][product.id] = _get_tax_percent(product_taxes)
        return taxes, tax_keys
