import uuid

from odoo import Command, api, fields, models
from odoo.exceptions import UserError, ValidationError

from odoo.addons.scrap_base.models.purchase_order import normalize_plate
from odoo.addons.web.controllers.utils import clean_action

# Suppliers found by a search on the screen
PARTNER_LIMIT = 60
# Products shown on the screen, in tiles by category
PRODUCT_LIMIT = 500
# Drafts shown when starting a purchase
DRAFT_LIMIT = 100
# Most lines of a purchase
MAX_LINES = 100
# Kinds of entry of the screen (`unbuild_type` of the purchase, see scrap_base): vehicles to
# dismantle, or to repair and sell whole
ENTRY_TYPES = ('main', 'refurbish')
# Longest license plate typed on the screen
MAX_LOT_NAME_LENGTH = 64


def is_record_id(value):
    """ Whether `value`, sent by the screen, can be a record id. """
    return isinstance(value, int) and not isinstance(value, bool) and value > 0


def is_number(value):
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def check_uuid(env, value):
    """ Return the uuid generated by the screen, or raise if it isn't one. """
    try:
        return str(uuid.UUID(value))
    except (TypeError, ValueError, AttributeError):
        raise ValidationError(env._("Invalid identifier of the operation.")) from None


class ScrapTouch(models.AbstractModel):
    """ Server side of the touch screen of the vehicle recycling.

    The screen loads what it shows with a few calls. The purchase being made is saved as a
    request for quotation in draft after each change, so that it can be resumed later, and
    "Purchase and receive" is a single call. The first save carries a uuid: sending it twice,
    after a double tap or a retry, updates the draft it created instead of duplicating it. The
    access rights of the user apply as in the backend.
    """
    _name = 'scrap.touch'
    _description = "Scrap Touch Screen"

    # ------------------------------------------------------------------
    # Loading
    # ------------------------------------------------------------------

    @api.model
    def get_screen_data(self):
        """ Products of the scrap entry, by category. """
        company = self.env.company
        products = self._get_entry_products()
        return {
            'currency_id': company.currency_id.id,
            'can_create_partner': self.env['res.partner'].has_access('create'),
            'partner_view_id': self.env.ref('scrap_touch.res_partner_view_form_scrap_touch').id,
            'products': [self._get_product_data(product) for product in products],
            'categories': [
                {'id': category.id, 'name': category.display_name}
                for category in products.categ_id.sorted('complete_name')
            ],
        }

    def _get_entry_product_domain(self):
        """ Products of the scrap entry: scrap templates, tracked by serial
        number (the license plate of each vehicle, as the chassis isn't known before
        receiving it). """
        return [
            ('is_template', '=', True),
            ('tracking', '=', 'serial'),
            *self.env['product.product']._check_company_domain(self.env.company),
        ]

    def _get_entry_products(self):
        return self.env['product.product'].search(
            self._get_entry_product_domain(), limit=PRODUCT_LIMIT, order='default_code, name, id')

    def _get_product_data(self, product):
        return {
            'id': product.id,
            'name': product.display_name,
            'default_code': product.default_code or '',
            'categ_id': product.categ_id.id,
            # Changes with the image, so that the browser cache is refreshed
            'image_unique': str(product.write_date) if product.image_128 else False,
        }

    @api.model
    def search_partners(self, query=''):
        """ Companies (and individuals) matching `query`, the most frequent suppliers first. """
        Partner = self.env['res.partner']
        domain = [('parent_id', '=', False), *Partner._check_company_domain(self.env.company)]
        query = query.strip() if isinstance(query, str) else ''
        if query:
            domain += ['|', '|', '|', ('name', 'ilike', query), ('ref', 'ilike', query),
                       ('vat', 'ilike', query), ('phone', 'ilike', query)]
        partners = Partner.search(domain, limit=PARTNER_LIMIT, order='supplier_rank desc, name, id')
        return [self._get_partner_data(partner) for partner in partners]

    def _get_partner_data(self, partner):
        return {
            'id': partner.id,
            'name': partner.name,
            'city': partner.city or '',
            'vat': partner.vat or '',
        }

    def _get_partner(self, partner_id):
        if not is_record_id(partner_id):
            raise ValidationError(self.env._("Invalid supplier."))
        partner = self.env['res.partner'].browse(partner_id).exists()
        if not partner:
            raise ValidationError(self.env._("The supplier doesn't exist anymore."))
        partner.check_access('read')
        return partner.commercial_partner_id

    # ------------------------------------------------------------------
    # Drafts: the purchase being made is saved as a request for quotation in draft
    # ------------------------------------------------------------------

    @api.model
    def get_drafts(self, query='', state_filter='draft', unbuild_type='main'):
        """ Purchases of vehicles of a kind of entry, the last changed first: an entry starts
        by resuming one in draft, or a new one; the confirmed ones can be looked up, received
        and invoiced.

        :param str unbuild_type: kind of entry, 'main' (to dismantle) or 'refurbish' (to repair
            and sell whole)

        :param str state_filter: 'draft' (in progress: the drafts made on the screen),
            'to_receive' (confirmed with a receipt still to validate), 'to_invoice' (confirmed and
            not fully invoiced) or 'all' (every one but the cancelled ones)
        """
        state_domains = {
            'draft': [('state', '=', 'draft'), ('scrap_touch_uuid', '!=', False)],
            'to_receive': [('state', '=', 'purchase'), ('picking_ids', 'any', [('state', 'not in', ('done', 'cancel'))])],
            'to_invoice': [('state', '=', 'purchase'), ('invoice_status', '=', 'to invoice')],
            'all': [('state', '!=', 'cancel')],
        }
        if state_filter not in state_domains:
            raise ValidationError(self.env._("Invalid filter."))
        domain = [
            *state_domains[state_filter],
            ('unbuild_type', '=', self._check_entry_type(unbuild_type)),
            ('company_id', '=', self.env.company.id),
        ]
        query = query.strip() if isinstance(query, str) else ''
        if query:
            domain += ['|', '|', '|', ('name', 'ilike', query), ('partner_id', 'ilike', query),
                       ('order_line.scrap_lot_name', 'ilike', normalize_plate(query) or query),
                       ('picking_ids.move_line_ids.lot_id.name', 'ilike', normalize_plate(query) or query)]
        orders = self.env['purchase.order'].search(domain, limit=DRAFT_LIMIT, order='write_date desc, id desc')
        return [{
            'id': order.id,
            'name': order.name,
            'partner': order.partner_id.display_name,
            'date': fields.Datetime.to_string(order.write_date),
            'user': order.user_id.name or '',
            'amount_untaxed': order.amount_untaxed,
            'line_count': len(order.order_line.filtered(lambda line: not line.display_type)),
            **self._get_order_states(order),
        } for order in orders]

    def _get_order_states(self, order):
        """ State, receipt and invoice status of a purchase, with their labels as in the
        backend. """
        fields_info = order.fields_get(['state', 'invoice_status'], ['selection'])
        labels = {name: dict(info['selection']) for name, info in fields_info.items()}
        pickings = order.picking_ids.filtered(lambda picking: picking.state != 'cancel')
        return {
            'state': order.state,
            'state_label': labels['state'].get(order.state, ''),
            'invoice_status': order.invoice_status or False,
            'invoice_status_label': labels['invoice_status'].get(order.invoice_status, '') if order.state == 'purchase' else '',
            'to_receive': order.state == 'purchase' and any(picking.state != 'done' for picking in pickings),
            'received': bool(pickings) and all(picking.state == 'done' for picking in pickings),
        }

    @api.model
    def get_draft(self, order_id):
        """ A purchase in draft to go on with: its supplier and its lines. """
        return self._get_draft_data(self._get_draft(order_id))

    @api.model
    def save_draft(self, vals):
        """ Save the purchase being made, so that it can be resumed later. The first save
        creates it; the next ones update its lines: the lines known by the screen (`line_id`)
        are updated, the new ones added and the missing ones removed. The lines of other
        products, added in the backend, are kept.

        :param dict vals: {
            'uuid': identifier of the purchase, made by the screen,
            'partner_id': supplier,
            'unbuild_type': kind of entry, 'main' (to dismantle, by default) or 'refurbish'
                (to repair and sell whole),
            'order_id': the draft, once created,
            'lines': [{
                'line_id': line of the draft (optional),
                'product_id': product of the scrap entry,
                'price_unit': price, 0 or more,
                'lot_name': license plate, used as serial number,
            }, ...],
        }
        :return: the draft, with the id of each line in the order of the lines sent
        """
        order, line_ids = self._save_draft(vals)
        return dict(self._get_draft_data(order), line_ids=line_ids)

    @api.model
    def cancel_draft(self, order_id):
        """ Cancel a purchase in draft that won't go on. """
        self._get_draft(order_id).button_cancel()
        return True

    def _get_draft(self, order_id):
        if not is_record_id(order_id):
            raise ValidationError(self.env._("Invalid purchase."))
        order = self.env['purchase.order'].browse(order_id).exists()
        if not order:
            raise ValidationError(self.env._("The purchase doesn't exist anymore."))
        order.check_access('write')
        if order.state != 'draft':
            raise UserError(self.env._("%s is not in draft anymore.", order.name))
        return order

    def _find_order(self, vals):
        """ The purchase of the screen: the one resumed, or the one created with its uuid. """
        if vals.get('order_id') is not None:
            if not is_record_id(vals['order_id']):
                raise ValidationError(self.env._("Invalid purchase."))
            return self.env['purchase.order'].browse(vals['order_id']).exists()
        operation_uuid = check_uuid(self.env, vals.get('uuid'))
        return self.env['purchase.order'].search([('scrap_touch_uuid', '=', operation_uuid)], limit=1)

    def _check_entry_type(self, unbuild_type):
        if unbuild_type not in ENTRY_TYPES:
            raise ValidationError(self.env._("Invalid kind of entry."))
        return unbuild_type

    def _save_draft(self, vals):
        if not isinstance(vals, dict):
            raise ValidationError(self.env._("Invalid operation."))
        operation_uuid = check_uuid(self.env, vals.get('uuid'))
        partner = self._get_partner(vals.get('partner_id'))
        unbuild_type = self._check_entry_type(vals.get('unbuild_type', 'main'))
        order = self._find_order(vals)
        if order:
            order = self._get_draft(order.id)
            if order.partner_id.commercial_partner_id != partner:
                raise ValidationError(self.env._("The supplier of a purchase can't be changed."))
            if order.unbuild_type and order.unbuild_type != unbuild_type:
                raise ValidationError(self.env._("%s is of another kind of entry.", order.name))
            if not order.unbuild_type:
                order.unbuild_type = unbuild_type
            lines = self._prepare_lines(vals.get('lines'), order)
            before = order.order_line
            order.write({'order_line': self._get_draft_line_commands(order, lines)})
        else:
            lines = self._prepare_lines(vals.get('lines'))
            before = self.env['purchase.order.line']
            order = self.env['purchase.order'].create({
                'partner_id': partner.id,
                'scrap_touch_uuid': operation_uuid,
                'unbuild_type': unbuild_type,
                'order_line': [Command.create(self._get_draft_line_vals(line)) for line in lines],
            })
        # The new lines are created in the order of the lines of the screen
        created = iter((order.order_line - before).sorted('id'))
        line_ids = [
            line['line_id'] if line.get('line_id') in before.ids else next(created).id
            for line in lines
        ]
        return order, line_ids

    def _prepare_lines(self, lines, order=None):
        """ Check the lines sent by the screen. A license plate can be in one line only. """
        if not isinstance(lines, list) or len(lines) > MAX_LINES:
            raise ValidationError(self.env._("Add between 1 and %s lines.", MAX_LINES))
        serials = set()
        prepared = []
        for line in lines:
            if not isinstance(line, dict):
                raise ValidationError(self.env._("Invalid line."))
            product = self._get_entry_product(line.get('product_id'))
            price_unit = line.get('price_unit')
            if not is_number(price_unit) or price_unit < 0:
                raise ValidationError(self.env._("Enter a price of 0 or more."))
            lot_name = self._check_lot_name(product, line.get('lot_name'))
            if lot_name in serials:
                raise ValidationError(self.env._("The license plate %s is in more than one line.", lot_name))
            serials.add(lot_name)
            line_id = line.get('line_id')
            if line_id is not None and not (order and line_id in order.order_line.ids):
                line_id = None
            prepared.append({'line_id': line_id, 'product': product, 'price_unit': price_unit, 'lot_name': lot_name})
        return prepared

    def _get_entry_product(self, product_id):
        if not is_record_id(product_id):
            raise ValidationError(self.env._("Invalid product."))
        product = self.env['product.product'].search([('id', '=', product_id)])
        if not product:
            raise ValidationError(self.env._("The product doesn't exist anymore."))
        if not product.filtered_domain(self._get_entry_product_domain()):
            raise ValidationError(self.env._(
                "%s is not a scrap template that can be bought tracked by serial number.",
                product.display_name))
        return product

    def _check_lot_name(self, product, lot_name):
        """ The license plate of the line, its serial number, which must be typed and belong to
        one vehicle only: `product`, once its purchase is confirmed and it is a vehicle of its
        own (see scrap_base), or none yet. """
        lot_name = normalize_plate(lot_name)
        if not lot_name:
            raise ValidationError(self.env._("Enter the license plate of %s.", product.display_name))
        if len(lot_name) > MAX_LOT_NAME_LENGTH:
            raise ValidationError(self.env._("The number can't be longer than %s characters.", MAX_LOT_NAME_LENGTH))
        vehicles = self.env['product.template']._scrap_find_vehicles(lot_name, self.env.company) - product.product_tmpl_id
        if vehicles:
            raise UserError(self.env._(
                "The license plate %(lot)s is already used by %(product)s.",
                lot=lot_name, product=vehicles[0].display_name))
        if self._find_received_lot(product, lot_name):
            raise UserError(self.env._(
                "The license plate %(lot)s of %(product)s was already received.",
                lot=lot_name, product=product.display_name))
        return lot_name

    def _find_received_lot(self, product, lot_name):
        """ A serial number `lot_name` of a scrap template or of a vehicle other than `product`:
        also the vehicles received before they were products of their own. """
        Lot = self.env['stock.lot']
        return Lot.search([
            ('name', '=', lot_name),
            ('product_id', '!=', product.id if product.scrap_template_id else False),
            '|', ('product_id.is_template', '=', True), ('product_id.scrap_template_id', '!=', False),
            *Lot._check_company_domain(self.env.company),
        ], limit=1)

    def _find_lot(self, product, lot_name):
        Lot = self.env['stock.lot']
        return Lot.search([
            ('product_id', '=', product.id),
            ('name', '=', lot_name),
            *Lot._check_company_domain(self.env.company),
        ], limit=1)

    def _get_entry_lines(self, order):
        """ Lines of the purchase managed by the screen: the ones of the products of the scrap
        entry and, once the purchase is confirmed, of the vehicles made from them (see
        scrap_base). """
        return order.order_line.filtered(lambda line: not line.display_type and (
            line.product_id.filtered_domain(self._get_entry_product_domain())
            or (line.product_id.scrap_template_id and line.product_id.tracking == 'serial')
        ))

    def _get_draft_line_commands(self, order, lines):
        """ Commands to make the lines of the draft match the ones of the screen. """
        entry_lines = self._get_entry_lines(order)
        kept = entry_lines.browse()
        commands = []
        for line in lines:
            current = entry_lines.filtered(lambda l: l.id == line['line_id']) - kept
            vals = self._get_draft_line_vals(line)
            if current and current.product_id == line['product']:
                kept |= current
                del vals['product_id']
                commands.append(Command.update(current.id, vals))
            else:
                # Also a line removed in the backend meanwhile: it comes back
                commands.append(Command.create(vals))
        commands += [Command.unlink(line.id) for line in entry_lines - kept]
        return commands

    def _get_draft_line_vals(self, line):
        return {
            'product_id': line['product'].id,
            'product_qty': 1.0,
            'price_unit': line['price_unit'],
            'scrap_lot_name': line['lot_name'],
        }

    def _get_draft_data(self, order):
        return {
            'id': order.id,
            'name': order.name,
            'partner': self._get_partner_data(order.partner_id.commercial_partner_id),
            'lines': [{
                'line_id': line.id,
                'product': self._get_product_data(line.product_id),
                'price': line.price_unit,
                'lot_name': line.scrap_lot_name or '',
            } for line in self._get_entry_lines(order)],
        }

    # ------------------------------------------------------------------
    # Purchase and receive
    # ------------------------------------------------------------------

    @api.model
    def purchase_entry(self, vals, receive=True):
        """ Buy the vehicles of the purchase: the draft is saved with the lines of the screen,
        then confirmed. With `receive`, its receipt is validated at once, each vehicle with its
        license plate as serial number; without it, the receipt waits for the vehicles, with
        their license plates already set.

        :param dict vals: as `save_draft`
        :param bool receive: whether the vehicles are received too
        """
        if not isinstance(vals, dict):
            raise ValidationError(self.env._("Invalid operation."))
        order = self._find_order(vals)
        if order and order.state in ('purchase', 'done'):
            # Sent twice, after a double tap or a retry: already bought
            return self._get_entry_result(order)
        order, _line_ids = self._save_draft(vals)
        lines = self._get_entry_lines(order)
        if not lines:
            raise ValidationError(self.env._("Add between 1 and %s lines.", MAX_LINES))
        # The license plates are checked again: one may have been received meanwhile
        for line in lines:
            self._check_lot_name(line.product_id, line.scrap_lot_name)
        order.button_confirm()
        if receive:
            self._receive(order, {line.id: line.scrap_lot_name for line in lines})
        return self._get_entry_result(order)

    def _receive(self, order, lot_names):
        """ Validate the receipt of the purchase with all its quantity, each line in its lot.

        :param dict lot_names: license plate of each line of the scrap entry, by its id
        """
        pickings = order.picking_ids.filtered(lambda picking: picking.state not in ('done', 'cancel'))
        if not pickings:
            # Services or consumables not received in stock: there is nothing to receive
            return
        for move in pickings.move_ids.filtered(lambda move: move.state not in ('done', 'cancel')):
            move.quantity = move.product_uom_qty
            if move.has_tracking:
                lot_name = lot_names.get(move.purchase_line_id.id)
                if not lot_name:
                    raise UserError(self.env._(
                        "The receipt of %s couldn't be validated: check it in the backend.", order.name))
                lot = self._find_lot(move.product_id, lot_name)
                move_lines = move.move_line_ids
                move_lines[1:].unlink()
                move_lines[:1].write({
                    'quantity': move.product_uom_qty,
                    **({'lot_id': lot.id} if lot else {'lot_name': lot_name}),
                })
            move.picked = True
        result = pickings.with_context(skip_sms=True, cancel_backorder=True).button_validate()
        if result is not True or any(picking.state != 'done' for picking in pickings):
            raise UserError(self.env._(
                "The receipt of %s couldn't be validated: check it in the backend.", order.name))

    # ------------------------------------------------------------------
    # Confirmed purchases: summary, receipt and bill
    # ------------------------------------------------------------------

    @api.model
    def get_order_summary(self, order_id):
        """ A confirmed purchase to look up: its vehicles, state, receipt and bills. """
        order = self._browse_order(order_id)
        order.check_access('read')
        return dict(self._get_entry_result(order), partner_data=self._get_partner_data(order.partner_id.commercial_partner_id))

    @api.model
    def receive_order(self, order_id):
        """ Receive the vehicles of a confirmed purchase, each with its license plate as serial
        number. """
        order = self._get_confirmed_order(order_id)
        lines = self._get_entry_lines(order)
        pending = order.picking_ids.move_ids.filtered(lambda move: move.state not in ('done', 'cancel'))
        if not pending:
            raise UserError(self.env._("There is nothing to receive in %s.", order.name))
        for line in lines.filtered(lambda line: line in pending.purchase_line_id):
            self._check_lot_name(line.product_id, line.scrap_lot_name)
        self._receive(order, {line.id: line.scrap_lot_name for line in lines})
        return self._get_entry_result(order)

    @api.model
    def invoice_order(self, order_id):
        """ The bill of a confirmed purchase, in draft, to review it in a dialog. """
        order = self._get_confirmed_order(order_id)
        if order.invoice_status != 'to invoice':
            raise UserError(self.env._("There is nothing to invoice in %s.", order.name))
        action = clean_action(order.action_create_invoice(), self.env)
        action['target'] = 'new'
        return action

    def _browse_order(self, order_id):
        if not is_record_id(order_id):
            raise ValidationError(self.env._("Invalid purchase."))
        order = self.env['purchase.order'].browse(order_id).exists()
        if not order:
            raise ValidationError(self.env._("The purchase doesn't exist anymore."))
        return order

    def _get_confirmed_order(self, order_id):
        order = self._browse_order(order_id)
        order.check_access('write')
        if order.state != 'purchase':
            raise UserError(self.env._("%s is not a confirmed purchase.", order.name))
        return order

    def _get_entry_result(self, order):
        move_lines = order.picking_ids.move_line_ids.filtered(lambda move_line: move_line.state == 'done')
        bills = order.invoice_ids.filtered(lambda move: move.state != 'cancel').sorted('id')
        fields_info = bills.fields_get(['state'], ['selection'])
        bill_states = dict(fields_info['state']['selection'])
        return {
            'id': order.id,
            'name': order.name,
            'model': order._name,
            'partner': order.partner_id.display_name,
            'lines': [{
                'product': line.product_id.display_name,
                'qty': line.product_qty,
                'uom': line.uom_id.name,
                'price_unit': line.price_unit,
                'subtotal': line.price_subtotal,
                'plate': line.scrap_lot_name or '',
                # Location of the vehicle, named after its license plate (see scrap_base)
                'location': line.product_id.scrap_location_id.sudo().display_name or '',
                'lots': move_lines.filtered(
                    lambda move_line: move_line.move_id.purchase_line_id == line
                ).lot_id.mapped('name'),
                # Internal references of the vehicles received (see scrap_base)
                'refs': move_lines.filtered(
                    lambda move_line: move_line.move_id.purchase_line_id == line
                ).lot_id.filtered('ref').mapped('ref'),
            } for line in order.order_line.filtered(lambda line: not line.display_type)],
            'amount_untaxed': order.amount_untaxed,
            'amount_total': order.amount_total,
            'pickings': order.picking_ids.filtered(lambda picking: picking.state != 'cancel').mapped('name'),
            'bills': [{
                'id': bill.id,
                'name': bill.name if bill.name and bill.name != '/' else self.env._("Draft bill"),
                'state': bill.state,
                'state_label': bill_states.get(bill.state, ''),
                'amount_total': bill.amount_total,
            } for bill in bills],
            **self._get_order_states(order),
        }
